# 3. Recórrer una llista amb for

# Concepte: Bucle for, llistes.

# Enunciat: Crea una llista amb tres animals de la teva elecció. 
# Utilitza un bucle for per recórrer la llista i imprimir cada 
# animal per pantalla amb el missatge "M'agrada el/la [animal]".

animals = ["gat", "gos", "lleó", "elefant"]

for animal in animals:
    print(f"M'agrada el/la {animal}")